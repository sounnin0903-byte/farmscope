// 지목명 → 내부 카테고리 변환
function toLandCat(type) {
  if (!type) return '밭';
  if (type.includes('답') || type.includes('논')) return '논';
  if (type.includes('과수')) return '과수';
  if (type.includes('시설') || type.includes('온실') || type.includes('하우스')) return '시설';
  return '밭';
}

// 시도·지목 기반 지역 평균값 + PNU로 필지별 미세 변동
function mockByRegion(pnu, landType, bjdCode) {
  const sigungu = pnu?.slice(0, 5) ?? bjdCode?.slice(0, 5) ?? '00000';
  const sido    = pnu?.slice(0, 2) ?? bjdCode?.slice(0, 2) ?? '00';
  const cat     = toLandCat(landType);
  const base    = (REGION_SOIL[sigungu] ?? REGION_SOIL[sido] ?? REGION_SOIL.default)[cat];
  const seed = parseInt(pnu?.slice(-2) ?? '50', 10) || 50;
  // ±4% 범위로 필지별 미세 변동
  const vary = (v) => Math.round((v * (1 + ((seed % 8) - 4) * 0.01)) * 10) / 10;
  return {
    pH:   vary(base.pH),
    om:   vary(base.om),
    phos: vary(base.phos),
    k:    vary(base.k),
    ca:   vary(base.ca),
    mg:   vary(base.mg),
  };
}

function status(val, low, high) {
  if (val < low) return '부족';
  if (val > high) return '과다';
  return '적정';
}

