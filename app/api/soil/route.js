// 토양 상태에 따라 N/P/K 보정 — 농촌진흥청 시비처방기준 보정계수 적용
function calcFertilizer(crop, { om, phos, k }) {
  const base = FERT_BASE[crop] ?? FERT_BASE['벼'];
  const r = (v) => Math.round(v * 10) / 10;
  const N = r(base.N * (status(om,   25,  35)  === '과다' ? 0.85 : 1.0));
  const P = r(base.P * (status(phos, 80,  550) === '부족' ? 1.3  : status(phos, 80, 550) === '과다' ? 0.5 : 1.0));
  const K = r(base.K * (status(k,    0.3, 0.6) === '부족' ? 1.3  : status(k,   0.3, 0.6) === '과다' ? 0.5 : 1.0));
  return { N, P, K };
}

async function fetchByBjdCode(KEY, bjdCode) {
  const url =
    `https://apis.data.go.kr/1390802/SoilEnviron/SoilExam/V2/getSoilExamList` +
    `?serviceKey=${KEY}&STDB_CD=${bjdCode}&Page_Size=1&Page_No=1`;
  const res  = await fetch(url);
  const text = await res.text();
  console.log('[soil] 법정동 응답:', text.slice(0, 300));
  const getTag = (tag) => text.match(new RegExp(`<${tag}[^>]*>(.*?)<\/${tag}>`, 's'))?.[1]?.trim() ?? null;
  return getTag('ph') ? {
    ph: getTag('ph'), om: getTag('om'), avphos: getTag('avphos'),
    exK: getTag('exK'), exCa: getTag('exCa'), exMg: getTag('exMg'),
    sampleYear: getTag('sampleYear'),
  } : null;
}

