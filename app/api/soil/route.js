export async function GET(request) {
  const { searchParams } = new URL(request.url);
  const pnu      = searchParams.get('pnu');
  const bjdCode  = searchParams.get('bjdCode');
  const landType = searchParams.get('type') ?? '';
  const crop     = searchParams.get('crop') ?? '벼';

  const KEY = process.env.SOIL_API_KEY;
  const validPnu = pnu && pnu !== 'null' && pnu.length === 19;
  console.log('[soil] pnu:', pnu, 'bjdCode:', bjdCode, 'type:', landType, 'crop:', crop);

  if (!KEY || !validPnu) {
    return NextResponse.json(buildMockResponse(pnu, landType, crop, bjdCode));
  }

  try {
    const url =
      `https://apis.data.go.kr/1390802/SoilEnviron/SoilExam/V2/getSoilExam` +
      `?serviceKey=${KEY}&PNU_CD=${pnu}&numOfRows=1&pageNo=1`;
    const res  = await fetch(url);
    const text = await res.text();
    console.log('[soil] 응답:', text.slice(0, 500));

    const getTag = (tag) => text.match(new RegExp(`<${tag}[^>]*>(.*?)<\/${tag}>`, 's'))?.[1]?.trim() ?? null;
    const ph   = getTag('ph');
    const item = ph ? {
      ph, om: getTag('om'), avphos: getTag('avphos'),
      exK: getTag('exK'), exCa: getTag('exCa'), exMg: getTag('exMg'),
      sampleYear: getTag('sampleYear'),
    } : null;

    if (!item && bjdCode && bjdCode !== 'null') {
      const bjdItem = await fetchByBjdCode(KEY, bjdCode).catch(() => null);
      if (bjdItem) {
        const pH   = parseFloat(bjdItem.ph     ?? 6.5);
        const om   = parseFloat(bjdItem.om     ?? 23);
        const phos = parseFloat(bjdItem.avphos ?? 119);
        const k    = parseFloat(bjdItem.exK    ?? 0.3);
        const ca   = parseFloat(bjdItem.exCa   ?? 4.7);
        const mg   = parseFloat(bjdItem.exMg   ?? 1.8);
        return NextResponse.json({
          examYear: bjdItem.sampleYear ?? '2022',
          pH,   phStatus: status(pH,   5.5, 7.0),
          om,   omStatus: status(om,   25,  35),
          phos, pStatus:  status(phos, 80,  150),
          k,    kStatus:  status(k,    0.3, 0.6),
          ca,   caStatus: status(ca,   5.0, 6.0),
          mg,   mgStatus: status(mg,   1.5, 2.0),
          fertilizer: calcFertilizer(crop, { om, phos, k }),
          areaAvg: true,
        });
      }
    }

    if (!item) {
      return NextResponse.json(buildMockResponse(pnu, landType, crop, bjdCode));
    }

    const pH   = parseFloat(item.ph     ?? 6.5);
    const om   = parseFloat(item.om     ?? 23);
    const phos = parseFloat(item.avphos ?? 119);
    const k    = parseFloat(item.exK    ?? 0.3);
    const ca   = parseFloat(item.exCa   ?? 4.7);
    const mg   = parseFloat(item.exMg   ?? 1.8);

    return NextResponse.json({
      examYear: item.sampleYear ?? '2022',
      pH,   phStatus: status(pH,   5.5, 7.0),
      om,   omStatus: status(om,   25,  35),
      phos, pStatus:  status(phos, 80,  150),
      k,    kStatus:  status(k,    0.3, 0.6),
      ca,   caStatus: status(ca,   5.0, 6.0),
      mg,   mgStatus: status(mg,   1.5, 2.0),
      fertilizer: calcFertilizer(crop, { om, phos, k }),
    });
  } catch (err) {
    return NextResponse.json({ ...buildMockResponse(pnu, landType, crop, bjdCode), error: err.message });
  }
}
